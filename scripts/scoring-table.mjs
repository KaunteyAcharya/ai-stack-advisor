// Prints the scoring rules as Markdown, or with --write updates the section in docs/METHODOLOGY.md
// between the SCORING-TABLE markers. A test checks the doc is in sync with engine/scoring.js.
import { readFileSync, writeFileSync } from "node:fs";
import { BASE_SCORES, RULES, CRITERIA } from "../engine/scoring.js";

export function scoringMarkdown() {
  const out = ["### Base scores (0–5, before rules)", "", "| Criterion | Option | Score | Reason |", "|---|---|---|---|"];
  for (const c of CRITERIA) {
    for (const [opt, [score, why]] of Object.entries(BASE_SCORES[c.id])) out.push(`| ${c.label} | ${opt} | ${score} | ${why} |`);
  }
  out.push("", "### Rules", "", "| Rule | Effect | Reason |", "|---|---|---|");
  for (const r of RULES) {
    const effects = [];
    for (const [crit, byOpt] of Object.entries(r.set || {})) effects.push(`${crit}: ${Object.entries(byOpt).map(([o, v]) => `${o}=${v}`).join(", ")}`);
    for (const [crit, byOpt] of Object.entries(r.add || {})) effects.push(`${crit}: ${Object.entries(byOpt).map(([o, v]) => `${o}${v > 0 ? "+" : ""}${v}`).join(", ")}`);
    if (r.exclude) effects.push(`exclude ${Object.keys(r.exclude).join(", ")}`);
    if (r.warnings) effects.push(`warn ${Object.keys(r.warnings).join(", ")}`);
    if (r.notes) effects.push(`note ${Object.keys(r.notes).join(", ")}`);
    out.push(`| \`${r.id}\` | ${effects.join("; ")} | ${r.why} |`);
  }
  return out.join("\n");
}

const START = "<!-- SCORING-TABLE:START (generated by scripts/scoring-table.mjs --write) -->";
const END = "<!-- SCORING-TABLE:END -->";

export function replaceSection(doc, table) {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < 0) throw new Error("Markers not found in METHODOLOGY.md");
  return doc.slice(0, a + START.length) + "\n" + table + "\n" + doc.slice(b);
}

if (process.argv[1]?.endsWith("scoring-table.mjs")) {
  const table = scoringMarkdown();
  if (process.argv.includes("--write")) {
    const path = new URL("../docs/METHODOLOGY.md", import.meta.url);
    writeFileSync(path, replaceSection(readFileSync(path, "utf8"), table));
    console.log("docs/METHODOLOGY.md scoring section updated");
  } else console.log(table);
}
